export function translate(lang, key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

export function translateIndicator(lang, label) {
  return lang === 'tl' ? INDICATORS_TL[label] || label : label;
}

// 'en' | 'tl'  (Settings > Language)
export function useLang() {
  const { language } = useApp();
  const lang = language === 'tl' ? 'tl' : 'en';
  return {
    lang,
    copyLang: lang === 'tl' ? 'fil' : 'en',   // key used by Pasteboard/SuspiciousCard/alerts copy
    t: (key, vars) => translate(lang, key, vars),
    ind: (label) => translateIndicator(lang, label),
  };
}